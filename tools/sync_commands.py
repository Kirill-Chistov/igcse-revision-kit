#!/usr/bin/env python3
"""Make the kit's commands (/setup, /revise, …) native slash commands in every common AI tool.

    python3 tools/sync_commands.py           # write the shims
    python3 tools/sync_commands.py --check   # exit 1 if any shim is missing or out of date (CI)

The commands themselves live in commands/<name>.md — the only place to edit them. Each one starts
with YAML front matter (name, description). This script writes a tiny pointer file per tool so the
command shows up in that tool's "/" menu:

    .claude/skills/<name>/SKILL.md     Claude Code / Claude desktop app
    .cursor/commands/<name>.md         Cursor
    .gemini/commands/<name>.toml       Gemini CLI
    .github/prompts/<name>.prompt.md   GitHub Copilot (VS Code)

Tools without native commands (Codex, Windsurf, chat apps) need nothing: AGENTS.md tells every
agent to open commands/<name>.md when the student types the command or asks in plain words.
Standard library only.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CMD = ROOT / "commands"
NOTE = "Generated by tools/sync_commands.py from commands/{n}.md. Edit that file, not this one."
DO = ("Read `commands/{n}.md` in this repository (and `AGENTS.md` if you have not read it this "
      "session), then follow it exactly.")
ARGS = "Treat any words typed after the command as its arguments."


def commands() -> list[tuple[str, str, str]]:
    out = []
    for f in sorted(CMD.glob("*.md")):
        m = re.match(r"---\n(.*?)\n---\n", f.read_text(encoding="utf-8"), re.S)
        if not m:
            sys.exit(f"{f.relative_to(ROOT)}: no YAML front matter")
        fm = m.group(1)
        name = re.search(r"^name:\s*(.+)$", fm, re.M)
        desc = re.search(r"^description:\s*(.+)$", fm, re.M)
        if not name or not desc or name.group(1).strip() != f.stem:
            sys.exit(f"{f.relative_to(ROOT)}: front matter needs name: {f.stem} and a description")
        out.append((f.stem, desc.group(1).strip(), fm))
    return out


def shims() -> dict[Path, str]:
    files = {}
    for n, desc, fm in commands():
        note, do = NOTE.format(n=n), DO.format(n=n)
        files[ROOT / ".claude/skills" / n / "SKILL.md"] = (
            f"---\n{fm}\n---\n\n<!-- {note} -->\n\n{do} {ARGS}\n")
        files[ROOT / ".cursor/commands" / f"{n}.md"] = f"<!-- {note} -->\n\n{do} {ARGS}\n"
        files[ROOT / ".gemini/commands" / f"{n}.toml"] = (
            f"# {note}\ndescription = {json.dumps(desc, ensure_ascii=False)}\n"
            f'prompt = """\n{do}\nArguments: {{{{args}}}}\n"""\n')
        files[ROOT / ".github/prompts" / f"{n}.prompt.md"] = (
            f"---\ndescription: {json.dumps(desc, ensure_ascii=False)}\n---\n\n<!-- {note} -->\n\n"
            f"{do.replace('`commands/' + n + '.md`', f'[commands/{n}.md](../../commands/{n}.md)')} {ARGS}\n")
    return files


def stale_dirs(want: dict[Path, str]) -> list[Path]:
    """Shims whose command no longer exists."""
    keep = set(want)
    found = [*ROOT.glob(".claude/skills/*/SKILL.md"), *ROOT.glob(".cursor/commands/*.md"),
             *ROOT.glob(".gemini/commands/*.toml"), *ROOT.glob(".github/prompts/*.prompt.md")]
    return [p for p in found if p not in keep]


def main(argv: list[str]) -> int:
    want = shims()
    bad = [p for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    extra = stale_dirs(want)
    if "--check" in argv:
        for p in bad:
            print(f"out of date: {p.relative_to(ROOT)}")
        for p in extra:
            print(f"no matching command: {p.relative_to(ROOT)}")
        if bad or extra:
            print("run: python3 tools/sync_commands.py")
            return 1
        print(f"{len(want)} command shims up to date")
        return 0
    for p in bad:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(want[p], encoding="utf-8")
    for p in extra:
        p.unlink()
        if p.name == "SKILL.md" and not any(p.parent.iterdir()):
            shutil.rmtree(p.parent)
    print(f"{len(bad)} written, {len(extra)} removed, {len(want)} in total")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
